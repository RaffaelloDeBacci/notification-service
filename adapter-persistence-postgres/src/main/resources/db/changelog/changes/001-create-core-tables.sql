CREATE TABLE notification_inbox (
    event_reference VARCHAR(64) PRIMARY KEY,
    idempotency_key VARCHAR(255) NOT NULL UNIQUE,
    message_type VARCHAR(64) NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(32) NOT NULL,
    failure_reason VARCHAR(1000),
    -- Lease: a DISPATCHING row whose claimed_at is older than the lease is reclaimable
    -- (crash recovery); claim_count caps reclaims of an event that keeps failing.
    claimed_at TIMESTAMP WITH TIME ZONE,
    claim_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notification_inbox_status_created_at
    ON notification_inbox (status, created_at);

CREATE TABLE dispatch_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(255) NOT NULL,
    customer_reference VARCHAR(64) NOT NULL,
    delivery_channel VARCHAR(32) NOT NULL,
    notification_target VARCHAR(320) NOT NULL,
    attempt_number INT NOT NULL,
    outcome VARCHAR(32) NOT NULL,
    error_details VARCHAR(1000),
    dispatched_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Supports the dispatcher's "already delivered?" check on re-processing;
-- partial because only successful attempts are ever looked up.
CREATE INDEX idx_dispatch_ledger_delivered
    ON dispatch_ledger (idempotency_key, customer_reference, delivery_channel, notification_target)
    WHERE outcome = 'DELIVERED';

CREATE TABLE audit_outbox (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    event_type VARCHAR(128) NOT NULL,
    aggregate_type VARCHAR(128) NOT NULL,
    -- Dispatch-attempt events use the idempotency key as aggregate id.
    aggregate_id VARCHAR(255) NOT NULL,
    actor VARCHAR(128) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE
);

-- Partial: the relay only ever scans unpublished rows, so the index stays
-- small regardless of how many rows have already been relayed.
CREATE INDEX idx_audit_outbox_unpublished
    ON audit_outbox (sequence)
    WHERE published_at IS NULL;

-- Supports the retention purge, which scans by publication time.
CREATE INDEX idx_audit_outbox_published_at
    ON audit_outbox (published_at)
    WHERE published_at IS NOT NULL;

CREATE TABLE distribution_list (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_reference VARCHAR(64) NOT NULL,
    delivery_channel VARCHAR(32) NOT NULL,
    notification_target VARCHAR(320) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_distribution_list_customer_reference
    ON distribution_list (customer_reference);

ALTER TABLE distribution_list
    ADD CONSTRAINT uq_distribution_list_customer_channel_target
    UNIQUE (customer_reference, delivery_channel, notification_target);
